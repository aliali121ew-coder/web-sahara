      'خزان البانزين@382 | 4.26@251 | 17,870@218 | خزان البفر@305 | 1@295 | قراءة المسطرة@83 | 100@60 | 58,256.20@154 | خزانـــات الكـــــــــاز@538 | خزان بيت@454',
