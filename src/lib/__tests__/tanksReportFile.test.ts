import { describe, expect, it } from 'vitest';
import { parseTanksSheet } from '../tanksReportFile';
import { detectKind } from '../bulkUpload';

// تخطيط ملف الخزانات (الورقة من اليمين لليسار؛ العمود الأخير اسم الخزان)
const rows: unknown[][] = [
  ['', 'مستوى الخزانات الرئيسية للنفط الاسود', '', '', ''],
  ['', 'نسبة امتلاء الخزان', 'الكمية', 'مستوى ارتفاع النفط', 'رقم الخزان'],
  ['', 0.27, 1253070, 540, 'الخزان الرئيسي 1'],
  ['', 0.38, '1,751,977.50', 755, 'الخزان الرئيسي 2'],
  ['', 0.84, 3903081, 1682, 'الخزان الرئيسي 3'],
  ['', 0.87, 4019106, 1732, 'الخزان الرئيسي 4'],
  ['', 0.96, 4453039.5, 1919, 'الخزان الرئيسي 5'],
  ['', 0.91, 4234912.5, 1825, 'الخزان الرئيسي  6'],
  ['', '', 32215187, 'المجموع', ''],
  ['', 'الكمية', 'الكمية في المتر الواحد', 'مستوى ارتفاع المنتج', 'رقم الخزان'],
  ['', 104695.22, 25787, 5.06, 'خزان الوفود اليومي'],
  ['', '', '', '', 'خزانات الكاز'],
  ['سعة الخزان الكلية', 'نسبة امتلاء المضوع', 'سعة الخزان', 'رقم الخزان', ''],
  ['', 0.94, 4233600, 'خزان رقم 1  (نفط اسود)', ''],
  [4499480, 0.93, 4200000, 'خزان رقم 2  (نفط اسود)', ''],
  ['', 0.37, 1680000, 'خزان رقم 3 ( كاز )', ''],
  ['', 0.93, 4166400, 'خزان رقم 4 ( نفط اسود )', ''],
  ['', 0.92, 12000, 'خزان رقم 5 ( كاز نضيف )', '']
];

describe('tanks file (bulk upload)', () => {
  it('reads the 9 black-oil tank quantities only, in order', () => {
    expect(parseTanksSheet(rows)).toEqual([1253070, 1751977.5, 3903081, 4019106, 4453039.5, 4234912.5, 4233600, 4200000, 4166400]);
  });
  it('missing tanks are null', () => {
    expect(parseTanksSheet(rows.slice(0, 5))).toEqual([1253070, 1751977.5, 3903081, null, null, null, null, null, null]);
  });
  it('is detected as a tanks file', () => {
    expect(detectKind(rows.map(r => r.join(' ')).join('\n')).kind).toBe('tanks');
  });
});
