import { describe, expect, it } from 'vitest';
import { parseTanksPdfRows, parseTanksSheet, type PdfItem } from '../tanksReportFile';
import { detectKind } from '../bulkUpload';

// تخطيط ملف الخزانات (الورقة من اليمين لليسار؛ العمود الأخير اسم الخزان)
const rows: unknown[][] = [
  ['', 'مستوى الخزانات الرئيسية للنفط الاسود', '', '', ''],
  ['', 'نسبة امتلاء الخزان', 'الكمية', 'مستوى ارتفاع النفط', 'رقم الخزان'],
  ['', 0.27, 1253070, 540, 'الخزان الرئيسي 1'],
  ['', 0.38, '1,751,977.50', 755, 'الخزان الرئيسي 2'],
  ['', 0.84, 3903081, 1682, 'الخزان الرئيسي 3'],
  ['', 0.87, 4019106, 1732, 'الخزان الرئيسي 4'],
  ['', 0.96, 4453039.5, 1919, 'الخزان الرئيسي 5'],
  ['', 0.91, 4234912.5, 1825, 'الخزان الرئيسي  6'],
  ['', '', 32215187, 'المجموع', ''],
  ['', 'الكمية', 'الكمية في المتر الواحد', 'مستوى ارتفاع المنتج', 'رقم الخزان'],
  ['', 104695.22, 25787, 5.06, 'خزان الوفود اليومي'],
  ['', '', '', '', 'خزانات الكاز'],
  ['سعة الخزان الكلية', 'نسبة امتلاء المضوع', 'سعة الخزان', 'رقم الخزان', ''],
  ['', 0.94, 4233600, 'خزان رقم 1  (نفط اسود)', ''],
  [4499480, 0.93, 4200000, 'خزان رقم 2  (نفط اسود)', ''],
  ['', 0.37, 1680000, 'خزان رقم 3 ( كاز )', ''],
  ['', 0.93, 4166400, 'خزان رقم 4 ( نفط اسود )', ''],
  ['', 0.92, 12000, 'خزان رقم 5 ( كاز نضيف )', '']
];

describe('tanks file (bulk upload)', () => {
  it('reads the 9 black-oil tank quantities only, in order', () => {
    expect(parseTanksSheet(rows)).toEqual([1253070, 1751977.5, 3903081, 4019106, 4453039.5, 4234912.5, 4233600, 4200000, 4166400]);
  });
  it('missing tanks are null', () => {
    expect(parseTanksSheet(rows.slice(0, 5))).toEqual([1253070, 1751977.5, 3903081, null, null, null, null, null, null]);
  });
  it('is detected as a tanks file', () => {
    expect(detectKind(rows.map(r => r.join(' ')).join('\n')).kind).toBe('tanks');
  });

  it('reads the same tanks from PDF text (no columns, by distance from the name)', () => {
    // x: اسم الخزان يمين الصفحة (700)، والأعمدة إلى يساره
    const r = (...items: [string, number][]): PdfItem[] => items.map(([str, x]) => ({ str, x }));
    const pdf: PdfItem[][] = [
      r(['مستوى الخزانات الرئيسية للنفط الاسود', 400]),
      r(['رقم الخزان', 700], ['مستوى ارتفاع النفط', 560], ['الكمية', 400], ['نسبة امتلاء الخزان', 220]),
      r(['الخزان الرئيسي 1', 700], ['540', 560], ['1,253,070.00', 400], ['27%', 220]),
      // الاسم مقسّم والرقم منفصل
      r(['الخزان', 720], ['الرئيسي', 690], ['2', 665], ['755', 560], ['1,751,977.50', 400], ['38%', 220]),
      r(['الخزان الرئيسي 3', 700], ['1682', 560], ['3,903,081.00', 400], ['84%', 220]),
      r(['الخزان الرئيسي 4', 700], ['1732', 560], ['4,019,106.00', 400], ['87%', 220]),
      r(['الخزان الرئيسي 5', 700], ['1919', 560], ['4,453,039.50', 400], ['96%', 220]),
      r(['الخزان الرئيسي 6', 700], ['1825', 560], ['4,234,912.50', 400], ['91%', 220]),
      r(['خزان البفر 1', 700], ['4.26', 560], ['17,870', 400], ['58,256.20', 220]),
      r(['خزان رقم 1 ( نفط اسود )', 700], ['4233600', 560], ['94%', 400]),
      r(['خزان رقم 2 ( نفط اسود )', 700], ['4200000', 560], ['93%', 400], ['4499480', 150]),
      r(['خزان رقم 3 ( كاز )', 700], ['1680000', 560], ['37%', 400]),
      r(['خزان رقم 4 ( نفط اسود )', 700], ['4166400', 560], ['93%', 400]),
      r(['خزان رقم 5 ( كاز نضيف )', 700], ['12000', 560], ['92%', 400])
    ];
    expect(parseTanksPdfRows(pdf)).toEqual([1253070, 1751977.5, 3903081, 4019106, 4453039.5, 4234912.5, 4233600, 4200000, 4166400]);
  });
});
