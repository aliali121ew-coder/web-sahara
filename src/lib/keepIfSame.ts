/**
 * محدِّث حالة يُبقي القيمة السابقة إن كانت مطابقة للجديدة، فلا تُعاد رسم الصفحة بلا داعٍ.
 * يُستخدم عند إعادة قراءة البيانات من localStorage: الصفحات المخفية (Activity) تفقد مستمعي الأحداث أثناء إخفائها،
 * فتعيد القراءة عند ظهورها وإلا بقيت على نسخة قديمة حتى إعادة تحميل التطبيق.
 */
export const keepIfSame = <T,>(next: T) => (prev: T): T =>
  prev === next || JSON.stringify(prev) === JSON.stringify(next) ? prev : next;
